# 공력 패널 저작 도구 — CAERO1 카드 생성·미러, W2GJ DMI 작성, 스플라인 절점 제안
"""Authoring helpers behind the GUI Panel tab (Qt-free, unit-testable).

Provides the text-generation and geometry logic for interactive panel
modeling:

- ``caero1_card_text`` / ``mirror_caero1``: CAERO1 bulk-data entries.
- ``w2gj_dmi_text``: writes a DMI W2GJ deck from per-CAERO airfoil
  camber (root/tip NACA), inverse of the solver's read path -- the
  written value is ``-flip * dz/dx`` so that both NastAero and
  MSC Nastran recover the camber slope with their own conventions.
- ``suggest_spline_nodes`` + ``set1_card_text`` / ``spline1_card_text``:
  pick structural nodes near a CAERO panel and emit SET1/SPLINE1.
"""
from __future__ import annotations

from typing import Dict, List, Sequence, Tuple

import numpy as np


# ---------------------------------------------------------------------------
# 8자 고정폭 카드 포맷
# ---------------------------------------------------------------------------
def _f8(v: float) -> str:
    """Format a float into <= 8 characters (Nastran small field).

    8자에 들어가는 가장 높은 소수 정밀도를 택한다.
    """
    for prec in range(6, -1, -1):
        s = f"%.{prec}f" % v
        if len(s) <= 8:
            # 가독성: 남는 소수 0 제거 (소수점 뒤 최소 한 자리 유지)
            if "." in s:
                s = s.rstrip("0")
                if s.endswith("."):
                    s += "0"
            return s
    s = ("%8.3g" % v).strip()
    return s[:8]


def format_card(fields: Sequence, cont_fields: int = 8) -> str:
    """Join card fields into fixed 8-char lines with blank continuations.

    fields[0] is the keyword; each line carries up to 9 fields
    (keyword/blank + 8 data fields).
    """
    strs: List[str] = []
    for f in fields:
        if isinstance(f, float):
            strs.append(_f8(f))
        elif f is None:
            strs.append("")
        else:
            strs.append(str(f))
    lines = []
    head, rest = strs[0], strs[1:]
    chunk = rest[:cont_fields]
    rest = rest[cont_fields:]
    lines.append("".join([f"{head:<8}"] + [f"{s:>8}" for s in chunk]).rstrip())
    while rest:
        chunk = rest[:cont_fields]
        rest = rest[cont_fields:]
        lines.append("".join([" " * 8] + [f"{s:>8}" for s in chunk]).rstrip())
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# CAERO1
# ---------------------------------------------------------------------------
def caero1_card_text(eid: int, pid: int, nspan: int, nchord: int,
                     p1: Sequence[float], chord1: float,
                     p4: Sequence[float], chord4: float,
                     igid: int = 1) -> str:
    """CAERO1 + continuation (X1..Z1 X12 / X4..Z4 X43)."""
    return format_card(
        ["CAERO1", eid, pid, "", nspan, nchord, "", "", igid,
         float(p1[0]), float(p1[1]), float(p1[2]), float(chord1),
         float(p4[0]), float(p4[1]), float(p4[2]), float(chord4)])


def mirror_caero1(eid: int, p1: Sequence[float], chord1: float,
                  p4: Sequence[float], chord4: float
                  ) -> Tuple[np.ndarray, float, np.ndarray, float]:
    """Mirror a CAERO1 definition across the XZ plane (y -> -y).

    P1(내측)/P4(외측) 역할을 유지한 채 y부호만 바꾼다 — 좌익식 정의가
    되며, 기하 법선이 뒤집히는 것은 솔버가 normal_flipped로 처리한다.
    """
    m1 = np.array([p1[0], -p1[1], p1[2]], dtype=float)
    m4 = np.array([p4[0], -p4[1], p4[2]], dtype=float)
    return m1, float(chord1), m4, float(chord4)


# ---------------------------------------------------------------------------
# W2GJ DMI 작성 (읽기 경로의 역변환)
# ---------------------------------------------------------------------------
def w2gj_dmi_text(boxes, caero_panels: dict, airfoil_config) -> str:
    """Write a DMI W2GJ deck from an airfoil camber assignment.

    The solver reads W2GJ as ``wash = -flip * value`` and targets
    ``wash == dz/dx`` (surface-slope convention), so the written value
    is ``-flip * dz/dx``.  Boxes without an assigned airfoil get 0.

    Parameters
    ----------
    boxes : list of AeroBox
        From generate_all_panels (ascending box-id j-set order).
    caero_panels : dict
        BDFModel.caero_panels.
    airfoil_config : PanelAirfoilConfig
        Per-CAERO root/tip airfoil assignment.
    """
    from .airfoil_camber import compute_camber_normalwash

    dzdx = compute_camber_normalwash(boxes, caero_panels, airfoil_config)
    flip = np.array([-1.0 if b.normal_flipped else 1.0 for b in boxes])
    values = -flip * dzdx

    n = len(boxes)
    lines = ["$ W2GJ camber/twist initial downwash (generated by NastAero)",
             format_card(["DMI", "W2GJ", 0, 2, 1, 0, "", n, 1])]
    # 컬럼 카드: DMI W2GJ 1 1 v1 v2 ... (첫 줄 5개, 연속줄 8개)
    col: List = ["DMI", "W2GJ", 1, 1] + [float(v) for v in values]
    lines.append(format_card(col))
    return "\n".join(lines) + "\n"



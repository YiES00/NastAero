# 스플라인 절점 제안
# ---------------------------------------------------------------------------
def hard_point_ids(model, min_valence: int = 6,
                   fold_angle_deg: float = 25.0) -> set:
    """Structurally 'hard' node IDs: spar caps, rib lines, junctions.

    A node is hard when it (a) belongs to a line element (CBAR/CBEAM/
    CROD -- spar caps and stiffeners), (b) lies on a fold line where
    attached shell normals disagree by more than ``fold_angle_deg``
    (skin-to-spar/rib web junctions), or (c) is shared by at least
    ``min_valence`` elements. These are the load-path nodes whose
    z-displacement carries the global surface (no local panel
    breathing) and which accept spline point forces without local
    skin deformation.

    Fold detection rejects *continuous curvature*: on a coarsely
    faceted curved surface (boom tube, leading-edge wrap of a closed
    tube) every node folds, so a fold node whose shell neighbors are
    all fold nodes is demoted -- a genuine web junction is a fold
    line isolated between flat regions.
    """
    from collections import defaultdict

    count: Dict[int, int] = defaultdict(int)
    normals: Dict[int, list] = defaultdict(list)
    neighbors: Dict[int, set] = defaultdict(set)   # 쉘 엣지 인접 절점
    hard: set = set()
    nodes = getattr(model, "nodes", {}) or {}

    def _xyz(nid):
        n = nodes.get(nid)
        if n is None:
            return None
        return np.asarray(getattr(n, "xyz_global", n.xyz), dtype=float)

    for e in (getattr(model, "elements", {}) or {}).values():
        nids = list(getattr(e, "node_ids", []) or [])
        for n in nids:
            count[n] += 1
        if e.type in ("CBAR", "CBEAM", "CROD"):
            hard.update(nids[:2])
        elif e.type in ("CQUAD4", "CQUAD8", "CTRIA3", "CTRIA6") \
                and len(nids) >= 3:
            p = [_xyz(n) for n in nids[:3]]
            if any(v is None for v in p):
                continue
            nrm = np.cross(p[1] - p[0], p[2] - p[0])
            mag = np.linalg.norm(nrm)
            if mag > 1e-12:
                nrm /= mag
                for n in nids:
                    normals[n].append(nrm)
            corner = nids[:4] if e.type in ("CQUAD4", "CQUAD8") else nids[:3]
            k = len(corner)
            for i in range(k):
                a, b = corner[i], corner[(i + 1) % k]
                neighbors[a].add(b)
                neighbors[b].add(a)

    cos_th = float(np.cos(np.radians(fold_angle_deg)))

    def _folds(nid) -> bool:
        ns = normals.get(nid, [])
        for i in range(len(ns)):
            for j in range(i + 1, len(ns)):
                if abs(float(np.dot(ns[i], ns[j]))) < cos_th:
                    return True
        return False

    fold_nodes = {nid for nid in normals if _folds(nid)}
    curved = {nid for nid in fold_nodes
              if neighbors.get(nid)
              and all(n in fold_nodes for n in neighbors[nid])}
    for nid, ns in normals.items():
        if nid in hard:
            continue
        if count[nid] >= min_valence:
            hard.add(nid)
            continue
        if nid in fold_nodes:
            # 이웃 전부가 꺾임이면 연속 곡면(붐/앞전 랩) → 배제
            if nid in curved:
                continue
            hard.add(nid)
    return hard


def curved_surface_node_ids(model, fold_angle_deg: float = 25.0) -> set:
    """연속 곡면(코스한 튜브 등)에 속한 절점 집합.

    꺾임 절점이면서 쉘 이웃 전부가 꺾임인 절점 — 붐 튜브·닫힌 앞전
    랩의 표면. 스플라인 하드포인트 배제와 PLOAD4 압력 매핑의 튜브
    제외가 공유하는 판정이다.
    """
    from collections import defaultdict

    normals: Dict[int, list] = defaultdict(list)
    neighbors: Dict[int, set] = defaultdict(set)
    nodes = getattr(model, "nodes", {}) or {}

    def _xyz(nid):
        n = nodes.get(nid)
        if n is None:
            return None
        return np.asarray(getattr(n, "xyz_global", n.xyz), dtype=float)

    for e in (getattr(model, "elements", {}) or {}).values():
        if e.type not in ("CQUAD4", "CQUAD8", "CTRIA3", "CTRIA6"):
            continue
        nids = list(getattr(e, "node_ids", []) or [])
        if len(nids) < 3:
            continue
        p = [_xyz(n) for n in nids[:3]]
        if any(v is None for v in p):
            continue
        nrm = np.cross(p[1] - p[0], p[2] - p[0])
        mag = np.linalg.norm(nrm)
